//! User turns from a Claude Code or Codex transcript (JSONL), cleaned for capture.
//!
//! Neither transcript format is a stable contract: unknown shapes yield fewer turns, never
//! an error. Only user turns are read. Assistant turns are the model's own claims, and
//! storing them is how a guess comes back next session as a remembered fact.

use std::io::{Read, Seek, SeekFrom};
use std::path::Path;

use serde_json::Value;

/// Only the tail of a long transcript is read.
const MAX_BYTES: u64 = 4 * 1024 * 1024;
const MIN_LINE_CHARS: usize = 12;

/// Harness bookkeeping that arrives as a user turn. None of it is something the user said.
const META_PREFIXES: &[&str] = &[
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<local-command-stdout>",
    "<local-command-caveat>",
    "<system-reminder>",
    "<task-notification>",
    "<user-prompt-submit-hook>",
    "<ide_",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "<environment_context>",
    "<antml",
    "<skill>",
    "<turn_aborted>",
    "<hook_prompt",
    "<external_",
    "<codex_internal_context",
    "<user_instructions>",
    "# AGENTS.md instructions",
    // Harness-authored continuations. Stored, one was recalled 73 times in a real store.
    "This session is being continued from a previous conversation",
    "Resume directly",
    "[Request interrupted by user",
    "[ASYNC DELEGATION",
    "Delegated task:",
    "Caveat: The messages below were generated by the user while running local commands",
];
const META_SPANS: &[&str] = &[
    "system-reminder",
    "task-notification",
    "local-command-stdout",
    "local-command-caveat",
    "pasted_content",
];

/// Cleaned user lines, oldest first, from the transcript at `path`.
#[must_use]
pub fn user_lines(path: &Path) -> Vec<String> {
    if read_head(path)
        .lines()
        .take(20)
        .any(|l| serde_json::from_str::<Value>(l.trim()).is_ok_and(|r| is_headless(&r)))
    {
        return Vec::new();
    }
    let Some(raw) = read_tail(path) else {
        return Vec::new();
    };
    let records: Vec<Value> = raw
        .lines()
        .filter_map(|l| serde_json::from_str(l.trim()).ok())
        .collect();
    records
        .iter()
        .filter_map(user_text)
        .filter_map(|t| clean(&t))
        .collect()
}

/// Cleans one user turn; `None` for harness bookkeeping and fragments.
#[must_use]
pub fn clean(text: &str) -> Option<String> {
    if is_meta(text) {
        return None;
    }
    let mut out = text.to_owned();
    for tag in META_SPANS {
        out = strip_spans(&out, tag);
    }
    let flat = out.split_whitespace().collect::<Vec<_>>().join(" ");
    if flat.chars().count() < MIN_LINE_CHARS {
        return None;
    }
    Some(if flat.ends_with(['.', '!', '?']) {
        flat
    } else {
        format!("{flat}.")
    })
}

fn is_meta(text: &str) -> bool {
    let t = text.trim_start();
    META_PREFIXES.iter().any(|p| t.starts_with(p))
}

/// Removes `<tag ...>...</tag ...>` spans; an unclosed span is left as written.
fn strip_spans(text: &str, tag: &str) -> String {
    let open = format!("<{tag}");
    let close = format!("</{tag}");
    let mut out = String::new();
    let mut rest = text;
    while let Some(start) = rest.find(&open) {
        let after = &rest[start..];
        let Some(end) = after.find(&close) else {
            break;
        };
        out.push_str(&rest[..start]);
        out.push(' ');
        let tail = &after[end..];
        rest = tail.find('>').map_or("", |gt| &tail[gt + 1..]);
    }
    out.push_str(rest);
    out
}

/// Sessions whose "user" turns are machine-written briefs: SDK-driven Claude Code runs,
/// `codex exec`, and Codex subagents (spawned workers, guardian reviews), whose parent
/// thread decides what is worth remembering.
fn is_headless(record: &Value) -> bool {
    if record
        .get("entrypoint")
        .and_then(Value::as_str)
        .is_some_and(|e| e.starts_with("sdk"))
    {
        return true;
    }
    if record.get("type").and_then(Value::as_str) != Some("session_meta") {
        return false;
    }
    let meta = record.get("payload").unwrap_or(&Value::Null);
    meta.get("originator").and_then(Value::as_str) == Some("codex_exec")
        || meta
            .get("source")
            .and_then(Value::as_object)
            .is_some_and(|s| s.contains_key("subagent"))
}

/// Codex tags each content block of a user message; only `user.*` blocks were typed by the
/// user (the rest are skills, hook prompts, app context injected under the user role).
fn user_kinds(msg: &Value) -> Option<Vec<bool>> {
    let kinds = msg
        .get("internal_chat_message_metadata_passthrough")?
        .get("content_item_kinds")?
        .as_array()?;
    Some(
        kinds
            .iter()
            .map(|k| k.as_str().is_some_and(|k| k.starts_with("user.")))
            .collect(),
    )
}

fn user_text(record: &Value) -> Option<String> {
    let flag = |k: &str| record.get(k).and_then(Value::as_bool) == Some(true);
    if flag("isMeta") || flag("isSidechain") || flag("isCompactSummary") {
        return None;
    }
    // Codex: {"type":"response_item","payload":{"type":"message","role":"user","content":[...]}}
    let msg = if record.get("type").and_then(Value::as_str) == Some("response_item") {
        let p = record.get("payload")?;
        (p.get("type").and_then(Value::as_str) == Some("message")).then_some(p)?
    } else {
        // Claude Code: {"type":"user","message":{"role":"user","content":...}}
        record.get("message")?
    };
    if msg.get("role").and_then(Value::as_str) != Some("user") {
        return None;
    }
    let kinds = user_kinds(msg);
    if kinds.as_ref().is_some_and(|k| !k.contains(&true)) {
        return None;
    }
    match msg.get("content")? {
        Value::String(s) => Some(s.clone()),
        Value::Array(blocks) => {
            let aligned = kinds.filter(|k| k.len() == blocks.len());
            let parts: Vec<&str> = blocks
                .iter()
                .enumerate()
                .filter(|(i, _)| aligned.as_ref().is_none_or(|k| k[*i]))
                .map(|(_, b)| b)
                .filter(|b| {
                    matches!(
                        b.get("type").and_then(Value::as_str),
                        Some("text" | "input_text")
                    )
                })
                .filter_map(|b| b.get("text").and_then(Value::as_str))
                .filter(|t| !is_meta(t))
                .collect();
            (!parts.is_empty()).then(|| parts.join("\n"))
        }
        _ => None,
    }
}

/// The first 64 KiB, where the session metadata lives.
fn read_head(path: &Path) -> String {
    let mut buf = Vec::new();
    if let Ok(f) = std::fs::File::open(path) {
        let _ = f.take(64 * 1024).read_to_end(&mut buf);
    }
    String::from_utf8_lossy(&buf).into_owned()
}

fn read_tail(path: &Path) -> Option<String> {
    let mut f = std::fs::File::open(path).ok()?;
    let len = f.metadata().ok()?.len();
    let start = len.saturating_sub(MAX_BYTES);
    f.seek(SeekFrom::Start(start)).ok()?;
    let mut buf = Vec::new();
    f.read_to_end(&mut buf).ok()?;
    let text = String::from_utf8_lossy(&buf).into_owned();
    // A cut-off first line is not JSON; drop it.
    Some(if start > 0 {
        text.split_once('\n')
            .map(|(_, t)| t.to_owned())
            .unwrap_or_default()
    } else {
        text
    })
}
